#!/usr/bin/env python3
"""Build ukunconferences.org from data/ and templates/.

Checks everything first and writes nothing if any check fails.
Run with --check to validate only. See README.md for the data format.
"""
import hashlib, json, re, sys
from pathlib import Path
from jinja2 import Environment, FileSystemLoader, select_autoescape

ROOT = Path(__file__).resolve().parent
MARK = "Generated by build.py"
REQUIRED = ("id", "series", "path", "year", "date", "location", "blurb", "source")
LINKS = ("sponsors", "notes", "writeups", "media", "links")
OPTIONAL = LINKS + ("order", "attendees", "website", "committee", "sessions", "rooms", "sessionGrid", "label")
# Sections named in the "fill the gaps" box when empty.
GAPS = {"committee": "committee", "sessions": "sessions", "notes": "notes taken",
        "writeups": "write-ups", "media": "photos and video"}
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()

errors = []


def is_web(u):
    return isinstance(u, str) and re.match(r"https?://\S+$", u)


def date_key(e):
    """(year, month, day) from free-text dates; unknown parts sort first."""
    m = next((i + 1 for i, n in enumerate(MONTHS) if n in e["date"]), 0)
    d = re.match(r"(\d{1,2})\b", e["date"])
    return (e["year"], m, int(d.group(1)) if d else 0)


def check(e, series, stem):
    bad = lambda msg: errors.append(f"{stem}.json: {msg}")
    for k in REQUIRED:
        if not e.get(k):
            bad(f"missing {k}")
    for k in set(e) - set(REQUIRED) - set(OPTIONAL):
        bad(f"unknown field {k!r}")
    if any(not e.get(k) for k in REQUIRED):
        return
    if e["id"] != stem:
        bad("id must match the file name")
    if e["series"] not in series:
        bad(f"unknown series {e['series']!r}")
    elif not re.fullmatch(re.escape(series[e["series"]]["slug"]) + r"/[a-z0-9-]+", e["path"]):
        bad(f"path must be {series[e['series']]['slug']}/<something>")
    for k in LINKS:
        for i in e.get(k, []):
            if not i.get("title") or not is_web(i.get("url")):
                bad(f"every entry in {k} needs a title and an http(s) url")
    for k in ("website", "sessionGrid"):
        if k in e and not is_web(e[k]):
            bad(f"{k} must be an http(s) url")
    for c in e.get("committee", []):
        if not c.get("name") or not is_web(c.get("source")):
            bad("every committee entry needs a name and a source url where it is already public")
    for slot in e.get("sessions", []):
        for i in slot["items"]:
            # Site policy: topics only, never who pitched them.
            if set(i) != {"room", "title"}:
                bad("sessions may only hold room and title (no pitchers' names)")
            elif not 0 <= i["room"] < len(e.get("rooms", [])):
                bad(f"room {i['room']} is not in rooms")


def main():
    series = json.loads((ROOT / "data/series.json").read_text())
    events = []
    for f in sorted((ROOT / "data/events").glob("*.json")):
        try:
            e = json.loads(f.read_text())
        except ValueError as x:
            errors.append(f"{f.name}: {x}")
            continue
        check(e, series, f.stem)
        events.append(e)
    paths = [e.get("path") for e in events]
    for p in {p for p in paths if paths.count(p) > 1}:
        errors.append(f"duplicate path {p}")
    if errors:
        sys.exit("\n".join(errors))
    if "--check" in sys.argv:
        print(f"{len(events)} events OK")
        return

    # Home-page order within a year: explicit `order`, then newest first.
    events.sort(key=lambda e: date_key(e), reverse=True)
    events.sort(key=lambda e: e.get("order", 10**6))

    out = {}
    home = [{k: v for k, v in e.items() if k not in ("source", "order")} for e in events]
    out["js/data.js"] = (f"// {MARK}: edit data/, not this file.\n"
                         f"const SERIES = {json.dumps(series, indent=1, ensure_ascii=False)};\n"
                         f"const EVENTS = {json.dumps(home, indent=1, ensure_ascii=False)};\n")
    ver = hashlib.sha256(out["js/data.js"].encode() + (ROOT / "js/app.js").read_bytes()
                         + (ROOT / "css/styles.css").read_bytes()).hexdigest()[:8]
    env = Environment(loader=FileSystemLoader(ROOT / "templates"), trim_blocks=True, lstrip_blocks=True,
                      autoescape=select_autoescape(["html", "j2"]))

    def render(name, url, **kw):
        return env.get_template(name).render(url=url, ver=ver, **kw) + "\n"

    out["index.html"] = render("home.html.j2", "/")
    urls = ["/"]
    for key, s in series.items():
        mine = sorted((e for e in events if e["series"] == key), key=date_key)
        for e in mine:
            many = sum(x["year"] == e["year"] for x in mine) > 1
            month = next((m for m in MONTHS if m in e["date"]), "")
            label = e.get("label") or (f"{e['year']} ({month})" if many and month else str(e["year"]))
            e["short_title"], e["title"] = label, f"{s['name']} {label}"
            e["session_count"] = sum(len(x["items"]) for x in e.get("sessions", []))
            e["missing"] = [v for k, v in GAPS.items() if not e.get(k)]
        for n, e in enumerate(mine):
            url = f"/{e['path']}/"
            urls.append(url)
            out[f"{e['path']}/index.html"] = render(
                "event.html.j2", url, e=e, s=s, prev=mine[n - 1] if n else None,
                next=mine[n + 1] if n + 1 < len(mine) else None)
        urls.append(f"/{s['slug']}/")
        out[f"{s['slug']}/index.html"] = render("series.html.j2", f"/{s['slug']}/", s=s, events=mine[::-1])
    out["sitemap.xml"] = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                          + "".join(f"  <url><loc>https://ukunconferences.org{u}</loc></url>\n" for u in urls)
                          + "</urlset>\n")

    # Pages we generated earlier whose event has gone.
    for f in ROOT.glob("*/**/index.html"):
        rel = f.relative_to(ROOT).as_posix()
        if rel not in out and not rel.startswith(".") and MARK in f.read_text()[:200]:
            f.unlink()
            print("removed", rel)
    for rel, text in out.items():
        f = ROOT / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        if not f.exists() or f.read_text() != text:
            f.write_text(text)
    print(f"built {len(events)} event pages, {len(series)} series pages")


main()
